'use strict';
// Reproducible field-card selection from the reviewed worksheet audit.
const fs=require('node:fs'),path=require('node:path'),root=path.resolve(__dirname,'..');
const dir=path.join(root,'Quest_Navigation/ProjectPBZ/PBZModLoader/mods/PBZQuestRoute');
const old=require(dir+'/PBZRouteSurveyTasks'),tables=require(dir+'/PBZRouteTables').data;
const audit=JSON.parse(fs.readFileSync(root+'/authoring/roadbook-course-audit.json'));
const existing=new Map(old.cards.map(c=>[c.id,c]));
const labels={chain:'锁链', 'red-thread-weapon':'红丝线影武装机关','flame-lion-weapon':'火狮影武装机关','mask-required':'面具条件',
 hook:'钩索','hook-required':'钩索','hook-shortcut':'钩索捷径',zipline:'滑索',elevator:'升降梯','locked-shortcut':'锁门近路',
 'locked-doors':'锁门','door-shortcut':'门捷径','eye-puzzle':'眼部机关'};
const excluded=new Set(['worksheet-014','worksheet-015','worksheet-016','worksheet-017']);
const cards=[{...existing.get('B03'),id:'B03',number:1,purpose:'缺连接对照',hints:['door'],sourceStatus:'field failure'}];
for(const row of audit.links){
 const a=tables.bells[row.from?.toLowerCase()],b=tables.bells[row.to?.toLowerCase()];
 if(!a||!b||a.world!==b.world||excluded.has(row.id)||row.status==='measured-reference'||
  Math.max(Math.abs(a.at[2]),Math.abs(b.at[2]))>100000||Math.hypot(...a.at.map((v,i)=>v-b.at[i]))>100000||
  row.hints.some(h=>/story-portal|world-transfer|ending-condition|chase/.test(h)))continue;
 const types=[...new Set(row.hints.map(h=>labels[h]).filter(Boolean))];
 if(row.runtimeEnabled&&!types.length)continue;
 const id='S'+row.id.split('-')[1],prior=existing.get(id)||{};
 cards.push({...prior,id,worksheet:row.id,from:row.from,to:row.to,purpose:row.runtimeEnabled?'验证现有候选':'补连续几何',
  sourceStatus:row.status,hints:row.hints,mechanisms:types,issue:types.length?types.join('、')+'：入口、动作、落脚和条件现场对照':prior.issue||'补齐真实连续道路与上下层连接'});
}
const legacy=['B03','S012','S018','S020','S030','S037','S040','S062','S072','S116','S128'];
cards.sort((a,b)=>{
 const rank=c=>legacy.includes(c.id)?legacy.indexOf(c.id):1000+Number(c.id.slice(1));return rank(a)-rank(b);
});
for(let i=0;i<cards.length;i++)cards[i].number=i+1;
const resolve=old.resolve.toString();
fs.writeFileSync(dir+'/PBZRouteSurveyTasks.js',"'use strict';\n// Generated by tools/build-survey-catalog.cjs; cards are evidence requests, not verified roads.\nexports.revision=1;\nexports.cards="+JSON.stringify(cards,null,1)+';\nexports.resolve='+resolve+';\n');
const resolved=require(dir+'/PBZRouteSurveyTasks');resolved.cards=cards;
const version=JSON.parse(fs.readFileSync(root+'/release/NEXUS-FIELDS.json')).version;
const resolvedCards=resolved.resolve(tables),mapIds=Object.fromEntries(['DengDingShanDao','DuanHunYa','FuJiZhiLin','HouJie','HuanShuShi','LuJiaCun','MeiGuHu','MeiGu_YiJi','PangZhen','XiGu','XiMeng','ZhengDaoDaYing'].map(id=>[id.toLowerCase(),id]));
const points=resolvedCards.flatMap(task=>['start','end'].map(role=>{
 const endpoint=task[role],map=mapIds[endpoint.area.toLowerCase()];if(!map)throw Error('Unresolved tracker map: '+endpoint.area);
 const key='pbz-survey:'+task.id.toLowerCase()+':'+role,name=task.number+'号路线'+(role==='start'?'开始':'结束');
 return {saveId:key,mapIds:[map],location:[endpoint.p.x,endpoint.p.y,endpoint.p.z],container:'loose',replaces:[],nodeGuids:[],
  contents:[{kind:'任务物品',id:key,nameText:name,icon:'/Game/PBZContent/UI/UINew/items/T_Icon_K_04901.T_Icon_K_04901'}],
  sourceHint:name+' · '+endpoint.name+'\n'+task.issue+'\n开始/结束点轻攻击；重攻击标错；防御标个人误走',
  survey:{id:task.id,number:task.number,role,revision:task.revision,name,world:task.world}};
}));
const payload=JSON.stringify({schema:1,points});if(payload.includes(']=]'))throw Error('Unsafe Lua data delimiter');
fs.writeFileSync(root+'/Quest_Navigation/platform/steam/ue4ss/Mods/PBZQuestRouteCompat/Scripts/PBZSurveyCatalogData.lua',
 "-- Generated navigation survey catalog; development package only.\nreturn assert(require('dkjson').decode([=["+payload+"]=]))\n");
fs.writeFileSync(root+'/authoring/development-survey-plan.json',JSON.stringify({schema:1,build:version,clientDate:'2026-11-15',timezone:'America/Tijuana',
 status:'implementation pending; no new field acceptance',sourceAudit:'authoring/roadbook-course-audit.json',scope:'Directed capture and candidate-validation tasks; no automatic runtime edges or accepted coverage.',
 capturedWorksheetExclusions:[...excluded],cards:resolvedCards},null,2)+'\n');
console.log('Survey cards:',cards.length,'Xigu:',cards.filter(c=>tables.bells[c.from.toLowerCase()]?.world==='pbz_xigu_wp').length);
