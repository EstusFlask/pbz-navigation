local Config=require('PBZRouteConfig')
local Core=require('PbzConfigCore')
local saved
local provider=Config.create({path='unused',read=function()end,write=function(v)saved=v end})
local schema=Core.compile(provider)
assert(schema.entries.ReverseSearch==nil and schema.groups.navigation==nil)
assert(provider.read().values.ReverseSearch==nil)
assert(not provider.apply({ReverseSearch=false}).ok,'retired setting was accepted')
assert(provider.apply({ThreadColor='red'}).ok)
assert(Config.create({path='unused',read=function()return saved end,write=function()end}).read().values.ThreadColor=='red')
local file=assert(io.open(config_test_root..'/navigation-roundtrip.json','wb'));file:write(saved);file:close()
assert(provider.reset('thread').ok)
assert(provider.read().values.ThreadColor=='blue')
assert(not provider.reset('navigation').ok)
print('PASS: current provider removes search direction and preserves rope settings')
